// Command gen turns spec/registry.yaml into the three artifacts that speak
// the semantic conventions (issue #5 §8, §10 decision 9).
//
//	format/semconv/registry_gen.go   the Go registry
//	analysis/semconv/keys.ts         the TypeScript lanes' key constants
//	docs/semconv/REGISTRY.md         the document a reader learns it from
//
// Usage:
//
//	go run ./spec/gen            # write the artifacts
//	go run ./spec/gen -check     # report drift, write nothing
//
// The generator owns those three files completely and nothing else. The value
// checkers stay hand-written in format/semconv/registry.go and are referenced
// by name from the spec; a name this program does not know fails codegen,
// which is what keeps "checked by the registry" from quietly meaning "checked
// by nothing".
//
// Output is a pure function of the spec: every listing is emitted in the
// spec's own order or in sorted order, no map is ranged over, and the Go
// artifact goes through go/format, so two runs on one spec produce identical
// bytes. spec/gen's test asserts exactly that, and asserts the committed
// artifacts equal what a run produces.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"sort"
	"strings"

	"gopkg.in/yaml.v3"
)

// The artifacts, by module-relative path. The generator writes these three and
// refuses to be pointed anywhere else.
const (
	specFile = "spec/registry.yaml"
	goFile   = "format/semconv/registry_gen.go"
	tsFile   = "analysis/semconv/keys.ts"
	mdFile   = "docs/semconv/REGISTRY.md"
)

// banner is the first line of every generated artifact, in that artifact's own
// comment syntax. The Go form is the one `go` tooling recognises.
const banner = "Code generated by spec/gen from spec/registry.yaml. DO NOT EDIT."

// checkers are the hand-written value checkers of format/semconv/registry.go,
// with how the generated registry calls each one. A spec entry naming anything
// else is a codegen failure rather than a key that checks nothing.
var checkers = map[string]func(k key) string{
	"enum": func(k key) string {
		names := make([]string, 0, len(k.Values))
		for _, v := range k.Values {
			names = append(names, v.Const)
		}
		return "enum(" + strings.Join(names, ", ") + ")"
	},
	"numbers":         func(k key) string { return fmt.Sprintf("numbers(%d)", k.Arity) },
	"slug":            func(key) string { return "slug" },
	"decimal":         func(key) string { return "decimal" },
	"positiveDecimal": func(key) string { return "positiveDecimal" },
	"huc12":           func(key) string { return "huc12" },
	"setName":         func(key) string { return "setName" },
}

type spec struct {
	Version      int    `yaml:"version"`
	VersionDoc   string `yaml:"version_doc"`
	Namespace    string `yaml:"namespace"`
	NamespaceDoc string `yaml:"namespace_doc"`

	Document struct {
		Title string `yaml:"title"`
		Intro string `yaml:"intro"`
		Rules string `yaml:"rules"`
	} `yaml:"document"`

	EntitiesDoc     string   `yaml:"entities_doc"`
	Entities        []entity `yaml:"entities"`
	StabilitiesDoc  string   `yaml:"stabilities_doc"`
	Stabilities     []named  `yaml:"stabilities"`
	VocabulariesDoc string   `yaml:"vocabularies_doc"`
	KeysDoc         string   `yaml:"keys_doc"`
	Keys            []key    `yaml:"keys"`
	PolicyKeysDoc   string   `yaml:"policy_keys_doc"`
	PolicyKeys      []key    `yaml:"policy_keys"`
}

type named struct {
	Name  string `yaml:"name"`
	Const string `yaml:"const"`
}

// vocab is one admitted value of an enum key: the string on the wire and the
// Go constant that spells it.
type vocab struct {
	Const string `yaml:"const"`
	Value string `yaml:"value"`
}

type entity struct {
	Name  string `yaml:"name"`
	Const string `yaml:"const"`
	What  string `yaml:"what"`
	Where string `yaml:"where"`
}

type key struct {
	Key       string  `yaml:"key"`
	Const     string  `yaml:"const"`
	Entity    string  `yaml:"entity"`
	Stability string  `yaml:"stability"`
	Check     string  `yaml:"check"`
	Values    []vocab `yaml:"values"`
	Arity     int     `yaml:"arity"`
	Doc       string  `yaml:"doc"`
	ValuesMD  string  `yaml:"values_md"`
	Meaning   string  `yaml:"meaning"`
}

func main() {
	check := flag.Bool("check", false, "report artifacts that are out of date; write nothing")
	root := flag.String("root", "", "repository root (default: the nearest directory above with a go.mod)")
	flag.Parse()

	dir, err := repoRoot(*root)
	if err != nil {
		fail(err)
	}
	artifacts, err := build(dir)
	if err != nil {
		fail(err)
	}

	stale := 0
	for _, path := range sorted(artifacts) {
		want := artifacts[path]
		full := filepath.Join(dir, filepath.FromSlash(path))
		have, readErr := os.ReadFile(full)
		if readErr == nil && bytes.Equal(have, want) {
			continue
		}
		stale++
		if *check {
			fmt.Fprintf(os.Stderr, "gen: %s is out of date; run `go generate ./format/semconv`\n", path)
			continue
		}
		if err := os.MkdirAll(filepath.Dir(full), 0o755); err != nil {
			fail(err)
		}
		if err := os.WriteFile(full, want, 0o644); err != nil {
			fail(err)
		}
		fmt.Fprintf(os.Stderr, "gen: wrote %s\n", path)
	}

	switch {
	case *check && stale > 0:
		os.Exit(1)
	case stale == 0:
		fmt.Fprintf(os.Stderr, "gen: %d artifacts already agree with %s\n", len(artifacts), specFile)
	}
}

func fail(err error) {
	fmt.Fprintln(os.Stderr, "gen:", err)
	os.Exit(1)
}

// build reads the spec under dir and renders every artifact. It is the whole
// program, factored out so the test can call it without a filesystem of its
// own beyond the repository it already sits in.
func build(dir string) (map[string][]byte, error) {
	raw, err := os.ReadFile(filepath.Join(dir, filepath.FromSlash(specFile)))
	if err != nil {
		return nil, fmt.Errorf("read the spec: %w", err)
	}
	var s spec
	decoder := yaml.NewDecoder(bytes.NewReader(raw))
	decoder.KnownFields(true)
	if err := decoder.Decode(&s); err != nil {
		return nil, fmt.Errorf("parse %s: %w", specFile, err)
	}
	if err := s.validate(); err != nil {
		return nil, fmt.Errorf("%s: %w", specFile, err)
	}
	goSource, err := s.goRegistry()
	if err != nil {
		return nil, err
	}
	return map[string][]byte{
		goFile: goSource,
		tsFile: s.tsKeys(),
		mdFile: s.document(),
	}, nil
}

// validate holds the spec to what the artifacts need before anything is
// rendered, so a malformed entry is one message rather than a compile error in
// generated code somebody then has to read.
func (s *spec) validate() error {
	if s.Version <= 0 {
		return fmt.Errorf("version must be positive, not %d", s.Version)
	}
	if s.Namespace == "" {
		return fmt.Errorf("namespace is empty")
	}
	entities := map[string]bool{}
	for _, e := range s.Entities {
		entities[e.Name] = true
	}
	stabilities := map[string]bool{}
	for _, t := range s.Stabilities {
		stabilities[t.Name] = true
	}

	seenKey, seenConst := map[string]bool{}, map[string]bool{}
	all := append(append([]key{}, s.Keys...), s.PolicyKeys...)
	for _, k := range all {
		if !strings.HasPrefix(k.Key, s.Namespace) {
			return fmt.Errorf("%s is outside the %q namespace", k.Key, s.Namespace)
		}
		if seenKey[k.Key] {
			return fmt.Errorf("%s is declared twice", k.Key)
		}
		if seenConst[k.Const] {
			return fmt.Errorf("the constant %s is declared twice", k.Const)
		}
		seenKey[k.Key], seenConst[k.Const] = true, true
	}
	for _, k := range s.Keys {
		if !entities[k.Entity] {
			return fmt.Errorf("%s attaches to %q, which is not a declared entity", k.Key, k.Entity)
		}
		if !stabilities[k.Stability] {
			return fmt.Errorf("%s carries stability %q, which is not a declared tier", k.Key, k.Stability)
		}
		if _, known := checkers[k.Check]; !known {
			return fmt.Errorf("%s is checked by %q, which is not a checker "+
				"format/semconv/registry.go writes", k.Key, k.Check)
		}
		if (k.Check == "enum") != (len(k.Values) > 0) {
			return fmt.Errorf("%s: an enum needs a vocabulary and nothing else may carry one", k.Key)
		}
		if (k.Check == "numbers") != (k.Arity > 0) {
			return fmt.Errorf("%s: an arity belongs to `numbers` and to nothing else", k.Key)
		}
		if k.ValuesMD == "" || k.Meaning == "" {
			return fmt.Errorf("%s has no documented values or meaning", k.Key)
		}
	}
	if len(s.Keys) > 0 && s.Keys[0].Doc == "" {
		return fmt.Errorf("the first key must carry a doc comment for the rest to join")
	}
	return nil
}

// entityConst and stabilityConst answer the Go constant a spec name maps to.
// validate has already established that both exist.
func (s *spec) entityConst(name string) string {
	for _, e := range s.Entities {
		if e.Name == name {
			return e.Const
		}
	}
	return ""
}

func (s *spec) stabilityConst(name string) string {
	for _, t := range s.Stabilities {
		if t.Name == name {
			return t.Const
		}
	}
	return ""
}

func (s *spec) goRegistry() ([]byte, error) {
	var b strings.Builder
	fmt.Fprintf(&b, "// %s\n\npackage semconv\n\n", banner)

	b.WriteString(comment(s.NamespaceDoc, ""))
	fmt.Fprintf(&b, "const Namespace = %q\n\n", s.Namespace)

	b.WriteString(comment(s.VersionDoc, ""))
	fmt.Fprintf(&b, "const Version = %d\n\n", s.Version)

	b.WriteString(comment(s.EntitiesDoc, ""))
	b.WriteString("const (\n")
	for _, e := range s.Entities {
		fmt.Fprintf(&b, "\t%s Entity = %q\n", e.Const, e.Name)
	}
	b.WriteString(")\n\n")

	b.WriteString(comment(s.StabilitiesDoc, ""))
	b.WriteString("const (\n")
	for _, t := range s.Stabilities {
		fmt.Fprintf(&b, "\t%s Stability = %q\n", t.Const, t.Name)
	}
	b.WriteString(")\n\n")

	b.WriteString(comment(s.KeysDoc, ""))
	b.WriteString("const (\n")
	for index, k := range s.Keys {
		// A key with no doc joins the comment above it, which is how two keys
		// that only make sense together are read together.
		if k.Doc != "" {
			if index > 0 {
				b.WriteString("\n")
			}
			b.WriteString(comment(k.Doc, "\t"))
		}
		fmt.Fprintf(&b, "\t%s = %q\n", k.Const, k.Key)
	}
	b.WriteString(")\n\n")

	for _, k := range s.PolicyKeys {
		b.WriteString(comment(k.Doc, ""))
		fmt.Fprintf(&b, "const %s = %q\n\n", k.Const, k.Key)
	}

	b.WriteString(comment(s.VocabulariesDoc, ""))
	b.WriteString("const (\n")
	groups := 0
	for _, k := range s.Keys {
		if len(k.Values) == 0 {
			continue
		}
		if groups > 0 {
			b.WriteString("\n")
		}
		groups++
		for _, v := range k.Values {
			fmt.Fprintf(&b, "\t%s = %q\n", v.Const, v.Value)
		}
	}
	b.WriteString(")\n\n")

	b.WriteString(comment("registry is the whole vocabulary, and it is generated: "+
		"spec/registry.yaml is the one source docs/semconv/REGISTRY.md and the "+
		"TypeScript lanes' key constants are cut from too.", ""))
	b.WriteString("var registry = map[string]definition{\n")
	for _, k := range s.Keys {
		fmt.Fprintf(&b, "\t%s: {%s, %s, %s},\n",
			k.Const, s.entityConst(k.Entity), s.stabilityConst(k.Stability), checkers[k.Check](k))
	}
	b.WriteString("}\n")

	source, err := format.Source([]byte(b.String()))
	if err != nil {
		return nil, fmt.Errorf("the generated Go does not parse: %w", err)
	}
	return source, nil
}

func (s *spec) tsKeys() []byte {
	var b strings.Builder
	fmt.Fprintf(&b, "// %s\n//\n", banner)
	b.WriteString(comment("The published attribute vocabulary, as the TypeScript lanes speak it "+
		"(issue #5 §3.2: analysis/ depends on its own math and the published attribute "+
		"vocabulary; render/ depends on analysis/ and published contracts). These are the "+
		"keys and nothing else -- no checker, no validation, no reader. A lane that wants "+
		"to know what a key means reads docs/semconv/REGISTRY.md, which is cut from the "+
		"same spec.", ""))

	b.WriteString("\n/** The namespace every governed key carries. */\n")
	fmt.Fprintf(&b, "export const NAMESPACE = %q;\n", s.Namespace)
	b.WriteString("\n/** The conventions version a bundle declares in its manifest. */\n")
	fmt.Fprintf(&b, "export const CONVENTIONS_VERSION = %d;\n", s.Version)

	for _, k := range s.Keys {
		b.WriteString("\n")
		b.WriteString(jsdoc(fmt.Sprintf("`%s`, %s. %s", k.Entity, k.Stability, k.Meaning)))
		fmt.Fprintf(&b, "export const %s = %q;\n", tsConst(k.Key, s.Namespace), k.Key)
	}
	return []byte(b.String())
}

func (s *spec) document() []byte {
	var b strings.Builder
	fmt.Fprintf(&b, "<!-- %s -->\n\n", banner)
	fmt.Fprintf(&b, "# %s\n\n", s.fill(s.Document.Title))
	b.WriteString(strings.TrimRight(s.fill(s.Document.Intro), "\n"))

	b.WriteString("\n\n## Entities\n\n")
	b.WriteString("| Entity | What it is | Where its attributes ride |\n|---|---|---|\n")
	for _, e := range s.Entities {
		fmt.Fprintf(&b, "| `%s` | %s | %s |\n", e.Name, e.What, e.Where)
	}

	b.WriteString("\n## Attributes\n\n")
	b.WriteString("| Key | Entity | Values | Stability | Meaning |\n|---|---|---|---|---|\n")
	for _, k := range s.Keys {
		fmt.Fprintf(&b, "| `%s` | %s | %s | %s | %s |\n",
			k.Key, k.Entity, k.ValuesMD, k.Stability, k.Meaning)
	}

	if len(s.PolicyKeys) > 0 {
		fmt.Fprintf(&b, "\n## %s\n\n", s.PolicyKeysDoc)
		b.WriteString("| Name | Meaning |\n|---|---|\n")
		for _, k := range s.PolicyKeys {
			fmt.Fprintf(&b, "| `%s` | %s |\n", k.Key, k.Meaning)
		}
	}

	b.WriteString("\n## Rules\n\n")
	b.WriteString(strings.TrimRight(s.fill(s.Document.Rules), "\n") + "\n")
	return []byte(b.String())
}

// fill substitutes the one placeholder the document prose may carry, so the
// version number a reader sees is the version the code carries.
func (s *spec) fill(text string) string {
	return strings.ReplaceAll(text, "{{version}}", fmt.Sprint(s.Version))
}

// tsConst derives a TypeScript constant name from a key, so the two can never
// drift apart: atlas.geometry.equirect.px becomes KEY_GEOMETRY_EQUIRECT_PX.
func tsConst(key, namespace string) string {
	tail := strings.TrimPrefix(key, namespace)
	return "KEY_" + strings.ToUpper(strings.NewReplacer(".", "_", "-", "_").Replace(tail))
}

// comment renders prose as a Go comment block at an indent, wrapping greedily.
// A blank line in the spec is a paragraph break and survives as one.
func comment(text, indent string) string {
	var b strings.Builder
	for index, paragraph := range strings.Split(strings.TrimSpace(text), "\n") {
		if index > 0 {
			b.WriteString(indent + "//\n")
		}
		for _, line := range wrap(paragraph, 70) {
			b.WriteString(indent + "// " + line + "\n")
		}
	}
	return b.String()
}

// jsdoc renders one paragraph as a JSDoc block.
func jsdoc(text string) string {
	lines := wrap(strings.TrimSpace(text), 74)
	if len(lines) == 1 {
		return "/** " + lines[0] + " */\n"
	}
	var b strings.Builder
	b.WriteString("/**\n")
	for _, line := range lines {
		b.WriteString(" * " + line + "\n")
	}
	b.WriteString(" */\n")
	return b.String()
}

// wrap breaks a paragraph into lines of at most width runes, greedily. A word
// longer than the width gets a line of its own rather than being cut.
func wrap(paragraph string, width int) []string {
	words := strings.Fields(paragraph)
	if len(words) == 0 {
		return []string{""}
	}
	lines := []string{}
	line := words[0]
	for _, word := range words[1:] {
		if len([]rune(line))+1+len([]rune(word)) > width {
			lines = append(lines, line)
			line = word
			continue
		}
		line += " " + word
	}
	return append(lines, line)
}

func sorted(artifacts map[string][]byte) []string {
	out := make([]string, 0, len(artifacts))
	for path := range artifacts {
		out = append(out, path)
	}
	sort.Strings(out)
	return out
}

// repoRoot resolves the directory the module-relative artifact paths hang off.
func repoRoot(declared string) (string, error) {
	if declared != "" {
		return declared, nil
	}
	dir, err := os.Getwd()
	if err != nil {
		return "", fmt.Errorf("locate the repository root: %w", err)
	}
	for {
		if _, err := os.Stat(filepath.Join(dir, "go.mod")); err == nil {
			return dir, nil
		}
		parent := filepath.Dir(dir)
		if parent == dir {
			return "", fmt.Errorf("no go.mod above the working directory")
		}
		dir = parent
	}
}
